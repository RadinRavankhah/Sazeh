/**
 * Generates TypeScript types from the backend component registry.
 * Zero dependencies: reads apps/backend/apps/registry/components/*.json and
 * emits src/generated/catalog.ts (typed) + catalog.json (raw bundle).
 *
 * Run from this directory:  npm run generate
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const componentsDir = resolve(here, "../../../apps/backend/apps/registry/components");
const outDir = resolve(here, "../src/generated");

const jsonToTsType = (schema, required, indent) => {
  const lines = [];
  const props = schema.properties ?? {};
  const req = new Set(schema.required ?? []);

  for (const [key, propSchema] of Object.entries(props)) {
    let tsType;
    if (Array.isArray(propSchema.enum)) {
      tsType = propSchema.enum.map((v) => JSON.stringify(v)).join(" | ");
    } else {
      switch (propSchema.type) {
        case "string": tsType = "string"; break;
        case "integer":
        case "number": tsType = "number"; break;
        case "boolean": tsType = "boolean"; break;
        case "array": {
          const item = propSchema.items ?? {};
          if (item.type === "object" && item.properties) {
            tsType = nestedInterface(key, item, `${indent}  `);
          } else if (Array.isArray(item.enum)) {
            tsType = `(${item.enum.map((v) => JSON.stringify(v)).join(" | ")})[]`;
          } else {
            tsType = `${item.type === "integer" || item.type === "number" ? "number" : item.type === "boolean" ? "boolean" : "string"}[]`;
          }
          break;
        }
        case "object": tsType = "Record<string, unknown>"; break;
        default: tsType = "unknown";
      }
    }
    const opt = req.has(key) ? "" : "?";
    const docs = [];
    if (propSchema.maxLength) docs.push(`max ${propSchema.maxLength} chars`);
    if (propSchema.format) docs.push(`format: ${propSchema.format}`);
    if (propSchema.pattern) docs.push(`pattern: ${propSchema.pattern}`);
    const docLine = docs.length ? `  /** ${docs.join(", ")} */\n` : "";
    const def = propSchema.default !== undefined ? ` @default ${JSON.stringify(propSchema.default)}` : "";
    lines.push(`${docLine}  ${key}${opt}: ${tsType};${def ? ` //${def}` : ""}`);
  }
  return lines.join("\n");
};

const nestedInterface = (key, schema, indent) => {
  const inner = jsonToTsType(schema, schema.required ?? [], `${indent}  `);
  return `{\n${inner}\n${indent}}`;
};

const pascal = (name) => name.replace(/[^a-zA-Z0-9]/g, " ").split(" ")
  .filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("");

const files = readdirSync(componentsDir).filter((f) => f.endsWith(".json")).sort();
const components = files.map((f) =>
  JSON.parse(readFileSync(join(componentsDir, f), "utf8"))
);

mkdirSync(outDir, { recursive: true });

// Raw bundle — importable JSON for the SPA palette/inspector
writeFileSync(join(outDir, "catalog.json"), JSON.stringify(components, null, 2) + "\n");

// Typed catalog
const interfaces = components.map((c) => {
  const body = jsonToTsType(c.schema, c.schema.required ?? [], "");
  return [
    `/** ${c.description} */`,
    `export interface ${pascal(c.name)}Props {`,
    body,
    "}",
    "",
  ].join("\n");
}).join("\n");

const nameUnion = components.map((c) => `  | "${c.name}"`).join("\n");

const entries = components.map((c) => ({
  name: c.name,
  display_name: c.display_name,
  category: c.category,
  description: c.description,
  schema: c.schema,
  default_props: c.default_props,
  allowed_children: c.allowed_children,
  example_payload: c.example_payload ?? null,
}));

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate.mjs — do not edit by hand.
// Source of truth: apps/backend/apps/registry/components/*.json

${interfaces}
/** Names of every component in the launch registry (decision D2.1). */
export type ComponentName =
${nameUnion};

/** A node in a page tree — mirrors the backend JSONB shape. */
export interface ComponentInstance<P = Record<string, unknown>> {
  id: string;
  component: ComponentName | string;
  props: P;
  children: ComponentInstance[];
}

/** One registry entry as served by GET /api/v1/registry/components/{name}/ */
export interface RegistryEntry<P = Record<string, unknown>> {
  name: string;
  display_name: string;
  category: "primitive" | "composite";
  description: string;
  schema: Record<string, unknown>;
  default_props: Partial<P>;
  allowed_children: string[];
  example_payload: P | null;
}

/** Atomic tree patch operations — must match backend apps/sites/tree.py */
export type TreePatchOp =
  | { op: "update_props"; node_id: string; props: Record<string, unknown> }
  | { op: "insert"; parent_id: string; index?: number; component: string; props?: Record<string, unknown> }
  | { op: "delete"; node_id: string }
  | { op: "move"; node_id: string; new_parent_id: string; index?: number };

/** Site theme tokens (decision D2.2) — mirrors backend apps/sites/theme.py */
export interface SiteTheme {
  accent_color?: string;
  font_family?: "geist" | "inter" | "outfit" | "satoshi" | "system-ui";
  radius?: "none" | "sm" | "md" | "lg" | "full";
  heading_scale?: "compact" | "normal" | "large";
}

/** Full launch catalog, embedded for direct SPA consumption. */
export const CATALOG: RegistryEntry[] = ${JSON.stringify(entries, null, 2)} as RegistryEntry[];
`;

writeFileSync(join(outDir, "catalog.ts"), out);
console.log(`Generated catalog.ts + catalog.json from ${components.length} components.`);
